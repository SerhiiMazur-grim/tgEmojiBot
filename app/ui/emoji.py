def custom(emoji_id: str, alt: str = "🙂") -> str:
    return f'<tg-emoji emoji-id="{emoji_id}">{alt or "🙂"}</tg-emoji>'


def _get(name: str) -> Emo:
    try:
        return EMO[name]
    except KeyError:
        raise ValueError(f"нет эмодзи «{name}»") from None


def t(name: str) -> str:
    e = _get(name)
    if not e.text_id:
        raise ValueError(f"у «{name}» нет эмодзи для текста")
    return f'<tg-emoji emoji-id="{e.text_id}">{e.fallback}</tg-emoji>'


def icon(name: str) -> str:
    e = _get(name)
    if not e.button_id:
        raise ValueError(f"у «{name}» нет иконки для кнопки")
    return e.button_id
